  const menuButton = document.querySelector('.menu-toggle');
  const nav = document.querySelector('.main-nav');
  const langButtons = document.querySelectorAll('.lang-button');
  let currentLanguage = 'tr';

  function applyLanguage(language) {
    const dict = translations[language] || translations.tr;
    currentLanguage = language;
    document.documentElement.lang = language;
    document.title = dict.pageTitle;
    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute('content', dict.pageDescription);

    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const key = element.dataset.i18n;
      if (Object.prototype.hasOwnProperty.call(dict, key)) element.textContent = dict[key];
    });
    document.querySelectorAll('[data-i18n-html]').forEach((element) => {
      const key = element.dataset.i18nHtml;
      if (Object.prototype.hasOwnProperty.call(dict, key)) element.innerHTML = dict[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
      const key = element.dataset.i18nPlaceholder;
      if (Object.prototype.hasOwnProperty.call(dict, key)) element.placeholder = dict[key];
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
      const key = element.dataset.i18nAria;
      if (Object.prototype.hasOwnProperty.call(dict, key)) element.setAttribute('aria-label', dict[key]);
    });
    langButtons.forEach((button) => {
      const active = button.dataset.lang === language;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });
    if (menuButton) {
      const open = nav && nav.classList.contains('open');
      menuButton.setAttribute('aria-label', open ? dict.menuClose : dict.menuOpen);
    }
    const status = document.querySelector('#form-status');
    if (status) status.textContent = '';
  }

  langButtons.forEach((button) => button.addEventListener('click', () => applyLanguage(button.dataset.lang)));

  if (menuButton && nav) {
    menuButton.addEventListener('click', () => {
      const open = nav.classList.toggle('open');
      menuButton.setAttribute('aria-expanded', String(open));
      menuButton.setAttribute('aria-label', open ? translations[currentLanguage].menuClose : translations[currentLanguage].menuOpen);
    });
    nav.querySelectorAll('a').forEach((link) => link.addEventListener('click', () => {
      nav.classList.remove('open');
      menuButton.setAttribute('aria-expanded', 'false');
      menuButton.setAttribute('aria-label', translations[currentLanguage].menuOpen);
    }));
  }

  const year = document.querySelector('#year');
  if (year) year.textContent = new Date().getFullYear();

  const revealTargets = document.querySelectorAll('.two-column,.section-heading,.service-card,.manifesto-inner,.work-card,.steps article,.contact-grid');
  revealTargets.forEach((element) => element.classList.add('reveal'));
  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver((entries, currentObserver) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
          currentObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12 });
    revealTargets.forEach((element) => observer.observe(element));
  } else {
    revealTargets.forEach((element) => element.classList.add('visible'));
  }

  const form = document.querySelector('#contact-form');
  const status = document.querySelector('#form-status');
  if (form) form.addEventListener('submit', (event) => {
    event.preventDefault();
    if (!form.reportValidity()) return;
    const data = new FormData(form);
    const subjectValues = {
      tr: {festival:'Festival / Halk etkinliği',fair:'Fuar / Tanıtım günleri',production:'Sahne / Prodüksiyon',corporate:'Kurumsal etkinlik',other:'Diğer'},
      en: {festival:'Festival / Public event',fair:'Fair / Showcase',production:'Stage / Production',corporate:'Corporate event',other:'Other'}
    };
    const name = String(data.get('name') || '').trim();
    const email = String(data.get('email') || '').trim();
    const subjectType = subjectValues[currentLanguage][String(data.get('subject') || '')] || String(data.get('subject') || '');
    const message = String(data.get('message') || '').trim();
    const subject = encodeURIComponent(`MSM Events website enquiry: ${subjectType}`);
    const body = encodeURIComponent(`Name: ${name}\nEmail: ${email}\nProject type: ${subjectType}\n\nProject details:\n${message}`);
    if (status) status.textContent = translations[currentLanguage].emailOpening;
    window.location.href = `mailto:msmeventsonline@gmail.com?subject=${subject}&body=${body}`;
  });

  applyLanguage('tr');
